"""Marker extraction for the s23pmic / s23urs host tests (run by tests/c/run_c_tests.py).

Nothing in the production drivers is edited: the constants and SE8 register accesses that the live
drivers s23batt / s23touch / s23sensprobe / s23audio use today are extracted into generated includes,
so test_s23pmic_*.c can prove the new pure headers agree with what already runs on the phone.
If a define or call pattern disappears, extraction fails loudly.

Generated files (in the runner's temp dir):
  s23pmic_live_consts.inc  - X_<DRIVER>_<NAME> copies of TLMM / GENI / address constants
  s23pmic_live_access.inc  - X_SE8_ACCESS[] table of every SE8 register access in s23batt.c + s23touch.c
  s23pmic_live_tzpins.inc  - s23sensprobe.c IsTlmmPinReserved() renamed to X_SensprobeIsTlmmPinReserved()
"""
import os
import re

DEFINE_RE = r"^#define\s+{name}\s+(.+?)\s*(?:/\*.*)?$"

# (driver file relative to drivers/, prefix, [define names])
CONSTS = [
    ("s23batt/s23batt.c", "S23BATT",
     ["TLMM_PHYS_BASE", "TLMM_MAP_SIZE", "TLMM_GPIO206", "TLMM_GPIO207", "MAX77705_FG_ADDR", "MAX77705_CHG_ADDR"]),
    ("s23touch/s23touch.c", "S23TOUCH",
     ["TLMM_GPIO11", "TLMM_GPIO48", "TLMM_GPIO49", "TLMM_GPIO206", "TLMM_GPIO207"]),
    ("s23sensprobe/s23sensprobe.c", "SENSPROBE",
     ["PA_TLMM_BASE", "SZ_TLMM", "SE_GENI_M_CMD0", "SE_GENI_M_IRQ_STATUS", "SE_GENI_RX_FIFO_STATUS",
      "SE_GENI_TX_FIFOn", "SE_GENI_RX_FIFOn", "SE_I2C_TX_TRANS_LEN", "SE_I2C_RX_TRANS_LEN",
      "SE_I2C_SCL_COUNTERS", "GENI_SER_M_CLK_CFG", "GENI_FW_REVISION_RO", "GENI_IF_DISABLE_RO",
      "I2C_OP_WRITE", "I2C_OP_READ", "I2C_OP_STOP_ON_BUS", "I2C_STOP_STRETCH", "I2C_SLV_ADDR_SHFT",
      "PACKING_4X8_MSB_CFG0", "PACKING_4X8_MSB_CFG1", "I2C_100K_SER_M_CLK_CFG", "I2C_100K_SCL_COUNTERS",
      "M_CMD_DONE_EN", "M_CMD_OVERRUN_EN", "M_ILLEGAL_CMD_EN", "M_CMD_FAILURE_EN", "M_CMD_CANCEL_EN",
      "M_CMD_ABORT_EN", "M_GP_IRQ_0_EN", "M_GP_IRQ_1_EN", "M_GP_IRQ_3_EN", "M_GP_IRQ_4_EN"]),
    ("s23audio/s23aud_hw.c", "S23AUDIO",
     ["PACKING_4X8_MSB_CFG0", "PACKING_4X8_MSB_CFG1", "I2C_OP_WRITE", "I2C_OP_READ", "I2C_SLV_ADDR_SHFT",
      "I2C_STOP_STRETCH"]),
]

ACCESS_RE = re.compile(
    r"I2cReg(Read8|Read16LE|Write8|WriteBuf)\s*\(\s*tlmm,\s*(\w+),\s*(\w+),\s*"
    r"(MAX77705_FG_ADDR|MAX77705_CHG_ADDR|0x[0-9A-Fa-f]+u?),\s*(0x[0-9A-Fa-f]+)u?")

# bytes accessed per helper; WriteBuf counts only its first register (the length is a runtime value,
# the mailbox span is covered separately by the tests).
CALL_RE = re.compile(r"I2cReg\w+\s*\(\s*tlmm\s*,\s*(\w+)")

ACCESS_LEN = {"Read8": 1, "Read16LE": 2, "Write8": 1, "WriteBuf": 1}


def _int(expr):
    expr = expr.strip()
    if not re.fullmatch(r"[0-9A-Fa-fxXuUlL()*+<| ]+", expr):
        raise SystemExit(f"extract_s23pmic: unexpected define expression {expr!r}")
    return eval(re.sub(r"(?<=[0-9A-Fa-f])[uUlL]+", "", expr), {"__builtins__": {}})  # digits/ops only


def extract(outdir, helpers):
    read, function, drivers = helpers["read"], helpers["function"], helpers["DRIVERS"]
    texts = {}
    lines = ["/* generated by tests/c/extract_s23pmic.py from live drivers - do not edit */"]
    for rel, prefix, names in CONSTS:
        text = texts.setdefault(rel, read(os.path.join(drivers, rel)))
        for n in names:
            m = re.search(DEFINE_RE.format(name=re.escape(n)), text, re.M)
            if not m:
                raise SystemExit(f"extract_s23pmic: #define {n} not found in drivers/{rel}")
            lines.append(f"#define X_{prefix}_{n} 0x{_int(m.group(1)):X}ull")
    with open(os.path.join(outdir, "s23pmic_live_consts.inc"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    batt = texts["s23batt/s23batt.c"]
    addr = {"MAX77705_FG_ADDR": _int(re.search(DEFINE_RE.format(name="MAX77705_FG_ADDR"), batt, re.M).group(1)),
            "MAX77705_CHG_ADDR": _int(re.search(DEFINE_RE.format(name="MAX77705_CHG_ADDR"), batt, re.M).group(1))}
    rows = []
    for rel, se8_sda in (("s23batt/s23batt.c", ("sda", "TLMM_GPIO206")), ("s23touch/s23touch.c", ("TLMM_GPIO206",))):
        text = texts[rel]
        # every SE8 call must have a literal address/register, else it would silently escape the policy check
        calls = sum(1 for s in CALL_RE.findall(text) if s in se8_sda)
        matched = sum(1 for g in ACCESS_RE.findall(text) if g[1] in se8_sda)
        if calls != matched:
            raise SystemExit(f"extract_s23pmic: drivers/{rel}: {calls} SE8 I2cReg*(tlmm,...) calls but only "
                             f"{matched} have a literal address/register")
        n = 0
        for m in ACCESS_RE.finditer(text):
            kind, sda, _scl, a, reg = m.groups()
            if sda not in se8_sda:
                continue  # e.g. PTN3222 on GPIO48/49 in s23touch.c - not SE8
            line = text.count("\n", 0, m.start()) + 1
            a7 = addr[a] if a in addr else _int(a)
            rows.append(f"    {{ 0x{a7:02X}u, 0x{_int(reg):02X}u, {ACCESS_LEN[kind]}u, {1 if 'Write' in kind else 0}u, "
                        f"\"{rel}:{line}\" }},")
            n += 1
        if n == 0:
            raise SystemExit(f"extract_s23pmic: no SE8 I2C accesses found in drivers/{rel}")
    with open(os.path.join(outdir, "s23pmic_live_access.inc"), "w", encoding="utf-8") as f:
        f.write("/* generated by tests/c/extract_s23pmic.py - every SE8 register access of s23batt/s23touch */\n")
        f.write("typedef struct { unsigned addr7, reg, len, is_write; const char *where; } x_se8_access;\n")
        f.write("static const x_se8_access X_SE8_ACCESS[] = {\n" + "\n".join(rows) + "\n};\n")

    sens = texts["s23sensprobe/s23sensprobe.c"]
    fn = function(sens, "static int IsTlmmPinReserved(uint16_t pin)", "IsTlmmPinReserved")
    fn = fn.replace("IsTlmmPinReserved", "X_SensprobeIsTlmmPinReserved")
    with open(os.path.join(outdir, "s23pmic_live_tzpins.inc"), "w", encoding="utf-8") as f:
        f.write("/* generated by tests/c/extract_s23pmic.py from drivers/s23sensprobe/s23sensprobe.c */\n" + fn)
